# encoding: UTF-8

module Test::Reporters

  # HTML Test Reporter
  #
  # Writes the run as one self-contained HTML document, once the run has
  # finished: a tally, then every result under the heading of its case.
  # Test output is captured and shown with the test that wrote it.
  #
  class Html < Abstract

    LABELS = {
      :pass  => 'PASS',
      :fail  => 'FAIL',
      :error => 'ERROR',
      :todo  => 'TODO',
      :skip  => 'SKIP'
    }

    ESCAPES = {
      '&' => '&amp;', '<' => '&lt;', '>' => '&gt;', '"' => '&quot;', "'" => '&#39;'
    }

    STYLE = <<-CSS
      :root { color-scheme: light dark; --pass: #1a7f37; --fail: #cf222e; --todo: #9a6700; --skip: #57606a; --line: #d0d7de; }
      @media (prefers-color-scheme: dark) { :root { --pass: #3fb950; --fail: #f85149; --todo: #d29922; --skip: #8b949e; --line: #30363d; } }
      body { font-family: system-ui, sans-serif; line-height: 1.5; max-width: 60rem; margin: 2rem auto; padding: 0 1rem; }
      h1 { margin-bottom: 0.25rem; }
      .tally { font-weight: bold; }
      .tally.passed { color: var(--pass); }
      .tally.failed { color: var(--fail); }
      section { border-left: 2px solid var(--line); padding-left: 1rem; margin: 1rem 0; }
      .result { margin: 0.25rem 0; }
      .status { display: inline-block; min-width: 3.5rem; font: bold 0.85em ui-monospace, monospace; }
      .pass .status { color: var(--pass); }
      .fail .status, .error .status { color: var(--fail); }
      .todo .status { color: var(--todo); }
      .skip .status { color: var(--skip); }
      .time, .reason, footer { color: var(--skip); font-size: 0.85em; }
      pre { margin: 0.25rem 0 0.5rem 3.5rem; padding: 0.5rem; border: 1px solid var(--line); overflow-x: auto; font-size: 0.85em; }
    CSS

    #
    def initialize(runner, output: $stdout)
      super(runner)
      @output = output
      @body   = []
      @depth  = 0
    end

    # Test output would otherwise land in the middle of the document.
    def capture_output?
      true
    end

    #
    def begin_suite(suite)
      @body  = []
      @depth = 0
    end

    #
    def begin_case(test_case)
      title, *rest = test_case.to_s.strip.split("\n")
      level = [@depth + 2, 6].min
      @body << %[<section class="case">]
      @body << %[<h#{level}>#{h title}</h#{level}>]
      @body << %[<p>#{rest.map{ |line| h(line.strip) }.join('<br>')}</p>] unless rest.empty?
      @depth += 1
    end

    #
    def end_case(test_case)
      @depth -= 1
      @body << %[</section>]
    end

    # Add a completed result to the document.
    def record(result)
      label = result.test.to_s.strip.split("\n").first.to_s
      label = "#{label} (case)" if result.kind == :case

      line  = %[<span class="status">#{LABELS.fetch(result.status)}</span> #{h label}]
      line << %[ <span class="reason">#{h result.reason}</span>] if result.status == :skip && result.reason
      line << %[ <span class="reason">#{h result.exception.message}</span>] if result.status == :todo && result.exception
      line << %[ <span class="time">#{'%.5fs' % result.elapsed}</span>]

      @body << %[<div class="result #{result.status}">#{line}]
      if [:fail, :error].include?(result.status)
        result.exceptions.each{ |exception| @body << %[<pre>#{h detail(exception, result.status == :error)}</pre>] }
      end
      @body << %[<pre class="stdout">#{h result.stdout}</pre>] unless result.stdout.empty?
      @body << %[<pre class="stderr">#{h result.stderr}</pre>] unless result.stderr.empty?
      @body << %[</div>]
    end

    # Write the document.
    def finish(summary)
      outcome = summary.success? ? 'passed' : 'failed'
      tally   = if summary.total.zero?
        'No tests were run.'
      else
        counts = ::Test::Result::STATUSES.map{ |status| "#{summary.counts[status]} #{TITLES[status]}" }
        "#{summary.total} tests: #{counts.join(', ')}."
      end

      @output.puts '<!DOCTYPE html>'
      @output.puts '<html lang="en">'
      @output.puts '<head>'
      @output.puts '<meta charset="utf-8">'
      @output.puts '<meta name="viewport" content="width=device-width, initial-scale=1">'
      @output.puts '<title>Test Report</title>'
      @output.puts "<style>\n#{STYLE.gsub(/^      /, '')}</style>"
      @output.puts '</head>'
      @output.puts '<body>'
      @output.puts '<h1>Test Report</h1>'
      @output.puts %[<p class="tally #{outcome}">#{h tally}</p>]
      @output.puts @body.join("\n") unless @body.empty?
      @output.puts %[<footer>Finished in #{'%.5fs' % summary.elapsed}. Generated by Rubytest #{h ::Test::VERSION} on #{h Time.now.strftime('%Y-%m-%d %H:%M:%S')}.</footer>]
      @output.puts '</body>'
      @output.puts '</html>'
    end

  private

    # Escape text for use in HTML.
    def h(text)
      text.to_s.gsub(/[&<>"']/, ESCAPES)
    end

    # An exception's class, message and where it was raised, with the rest
    # of its backtrace if asked.
    def detail(exception, backtrace=false)
      lines = ["#{exception.class}: #{exception.message}"]
      trace = exception.backtrace ? clean_backtrace(exception) : []
      trace = trace.first(1) unless backtrace
      lines.concat(trace.map{ |line| "  #{line}" })
      lines.join("\n")
    end

  end

end
